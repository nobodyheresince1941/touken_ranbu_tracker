type_of = {}
for t, s in types_raw.items():
    for n in s.split("•"):
        type_of[n.strip()] = t

def to_num(label):
    if label.startswith("〇"):
        return 0
    return int(re.match(r"(\d+)", label).group(1))

entries = []
for nums, names in rows:
    assert len(nums) == len(names)
    for l, n in zip(nums, names):
        entries.append((to_num(l), n))

groups = defaultdict(list)
order = []
for num, name in entries:
    if name not in groups:
        order.append(name)
    groups[name].append(num)

swords, warnings = [], []
for name in order:
    ids = sorted(groups[name])
    rec = {"id": ids[0], "name": name, "type": type_of.get(name, ""),
           "school": "", "kiwameId": None, "extraIds": []}
    if len(ids) == 2:
        rec["kiwameId"] = ids[1]
    elif len(ids) > 2:
        rec["extraIds"] = ids[1:]
        rec["note"] = "多个刀帐号指向同一页面，需手动核对哪一个是极"
        warnings.append(f"{name}: {ids}")
    if not rec["type"]:
        warnings.append(f"{name}: 没有匹配到刀种")
    swords.append(rec)

all_ids = {n for n, _ in entries}
gaps = [i for i in range(3, max(all_ids) + 1) if i not in all_ids]
in_nav_not_book = [n for n in type_of if n not in groups]

json.dump(swords, open("touken_swords.json", "w", encoding="utf-8"),
          ensure_ascii=False, indent=2)

print("刀帐条目数:", len(entries))
print("角色数:", len(swords))
print("有极的角色:", sum(1 for s in swords if s["kiwameId"]))
print("刀种统计:", {t: sum(1 for s in swords if s["type"] == t) for t in types_raw})
print("警告:", *warnings, sep="\n  ")
print("跳号:", gaps)
print("导航栏有但刀帐没有:", in_nav_not_book)
